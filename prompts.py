def _load_master() -> str:
    text = master_path().read_text(encoding="utf-8")
    # 「## ステップ4：出力フォーマット」〜 次の「## トーン」の直前までを職員モードの形式に差し替える
    fmt = STAFF_FORMAT.rstrip()
    if getattr(config, "INCLUDE_REWRITE", False):
        fmt += "\n" + REWRITE_FORMAT.rstrip()
    pattern = re.compile(r"## ステップ4：出力フォーマット.*?(?=\n## トーン)", re.S)
    if pattern.search(text):
        text = pattern.sub(lambda m: fmt, text)
    else:
        text += "\n\n" + fmt
    return text


def system_prompt() -> str:
    return STAFF_HEAD + "\n" + _load_master()


ES_TYPES = {
    "auto": "指定なし（内容から判定）",
    "gakuchika": "ガクチカ",
    "selfpr": "自己PR",
    "shibou": "志望動機",
    "other": "その他",
}


def user_prompt(data: dict) -> str:
    lines = ["次のESを添削してください。", ""]
    t = data.get("es_type", "auto")
    lines.append(f"- 種類：{ES_TYPES.get(t, ES_TYPES['auto'])}")
    if data.get("question"):
        lines.append(f"- 設問文：{data['question']}")
    if data.get("char_limit"):
        lines.append(f"- 文字数制限：{data['char_limit']}字")
    if data.get("company"):
        lines.append(f"- 応募先（企業・業界）：{data['company']}")
    if data.get("position"):
        lines.append(f"- 職種・コース・インターン等：{data['position']}")
    if data.get("grade"):
        lines.append(f"- 学年：{data['grade']}")
    if data.get("memo"):
        lines.append(f"- 職員からの補足（本人が面談で話したことなど。修正案に使ってよい）：{data['memo']}")
    lines.append(f"- 本文の文字数：{len(data.get('text', ''))}字")
    lines += ["", "--- ES本文 ---", data.get("text", "").strip(), "--- ここまで ---"]
    return "\n".join(lines)


